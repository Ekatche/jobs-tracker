import re
import unicodedata
from difflib import SequenceMatcher
from typing import Any, Dict, List, Optional, Set

from app.services.cv_templates import _date_key, _end_key

from .constants import (
    _LEVEL_WORDS,
    _POST_TEXT_KEYS,
    _ROMAN_NUMERALS,
    _SKIPPED_KEYS,
    ACTION_PREFIXES,
    STOPWORDS,
    TECHNICAL_SYNONYMS,
)


def _clean_str(s: str) -> str:
    """Normalizes string for comparison by lowercasing, stripping accents and punctuation."""
    if not s:
        return ""
    nfkd = unicodedata.normalize("NFKD", s)
    no_accents = "".join([c for c in nfkd if not unicodedata.combining(c)])
    cleaned = re.sub(r"[^\w\s]", " ", no_accents.lower())
    return re.sub(r"\s+", " ", cleaned).strip()


def _is_fuzzy_match(val: str, known_set: Set[str], threshold: float = 0.85) -> bool:
    """Checks if val is present in or closely matches any item in known_set."""
    clean_val = _clean_str(val)
    if not clean_val:
        return True
    for item in known_set:
        clean_item = _clean_str(item)
        if not clean_item:
            continue
        if clean_val == clean_item or clean_val in clean_item or clean_item in clean_val:
            return True
        if SequenceMatcher(None, clean_val, clean_item).ratio() >= threshold:
            return True
    return False


def _is_skill_supported(
    skill: str,
    known_skills: Set[str],
    profile_corpus: str,
    profile_tokens: Set[str],
    threshold: float = 0.82,
) -> bool:
    """Validates whether a skill generated by LLM is authentically grounded in the profile."""
    c_skill = _clean_str(skill)
    if not c_skill:
        return True
    if _is_fuzzy_match(skill, known_skills, threshold=threshold) or c_skill in profile_corpus:
        return True

    for act in ACTION_PREFIXES:
        if c_skill.startswith((f"{act} ", f"{act} d ", f"{act} de ")):
            words = c_skill[len(act) :].strip().split()
            while words and words[0] in STOPWORDS:
                words.pop(0)
            core = " ".join(words)
            if core and (core in profile_corpus or _is_fuzzy_match(core, known_skills, threshold=threshold)):
                return True
            if core in TECHNICAL_SYNONYMS and any(
                syn in profile_corpus or syn in known_skills for syn in TECHNICAL_SYNONYMS[core]
            ):
                return True

    for k, syns in TECHNICAL_SYNONYMS.items():
        if c_skill == k or c_skill in k or k in c_skill:
            if any(
                syn in profile_corpus or syn in known_skills or any(s in profile_tokens for s in syn.split())
                for syn in syns
            ):
                return True

    significant_tokens = [
        w for w in c_skill.split() if w not in STOPWORDS and w not in ACTION_PREFIXES and len(w) > 2
    ]
    if significant_tokens:
        matched = sum(
            1
            for w in significant_tokens
            if w in profile_tokens or any(SequenceMatcher(None, w, t).ratio() >= 0.88 for t in profile_tokens)
        )
        if matched == len(significant_tokens) or (
            len(significant_tokens) >= 3 and matched / len(significant_tokens) >= 0.75
        ):
            return True
    return False


def _profile_title(exp: Dict[str, Any]) -> str:
    return str(exp.get("role") or exp.get("title") or "").strip()


def _dates_agree(tailored: Optional[str], known: Optional[str], is_end: bool) -> bool:
    """Une date illisible ou une fin en cours concorde ; sinon même année et même mois."""
    key = _end_key if is_end else _date_key
    (tailored_year, tailored_month), (known_year, known_month) = key(tailored), key(known)
    if not tailored_year or not known_year or 9999 in (tailored_year, known_year):
        return True
    return tailored_year == known_year and (
        not tailored_month or not known_month or tailored_month == known_month
    )


def _is_skipped_key(key: Any) -> bool:
    return key in _SKIPPED_KEYS or (isinstance(key, str) and key.startswith(("_", "excluded_")))


def _collect_strings(data: Any) -> List[str]:
    if isinstance(data, str):
        return [data] if data.strip() else []
    if isinstance(data, list):
        return [s for item in data for s in _collect_strings(item)]
    if isinstance(data, dict):
        return [s for k, v in data.items() if not _is_skipped_key(k) for s in _collect_strings(v)]
    return []


def _significant_tokens(text: str) -> Set[str]:
    return {
        t
        for t in _clean_str(text).split()
        if t not in STOPWORDS and not re.fullmatch(r"(?:19|20)\d\d", t)
    }


def _all_tokens(text: str) -> Set[str]:
    """Jetons normalisés, élisions (« d' », « l' ») écartées."""
    return set(_clean_str(re.sub(r"\b[dDlL]['’]", " ", text)).split())


def _level_safe(a: str, b: str) -> bool:
    """La certification du CV (a) n'ajoute à (b) ni nombre, lettre isolée, chiffre romain ni niveau."""
    for tok in _all_tokens(a) - _all_tokens(b):
        if re.fullmatch(r"(?:19|20)\d\d", tok):
            continue
        if (
            any(ch.isdigit() for ch in tok)
            or len(tok) == 1
            or tok in _ROMAN_NUMERALS
            or tok in _LEVEL_WORDS
        ):
            return False
    return True


def _tokens_overlap(text: str, candidates: Set[str], both_ways: bool = True) -> bool:
    """Jetons significatifs inclus d'un côté ou de l'autre sans écart de niveau."""
    mine = _significant_tokens(text)
    return bool(mine) and any(
        theirs and (mine <= theirs or (both_ways and theirs <= mine)) and _level_safe(text, cand)
        for cand, theirs in ((c, _significant_tokens(c)) for c in candidates)
    )


def _cert_matches(cert: str, known_certs: Set[str]) -> bool:
    """Certification du profil : proximité de libellé ou de jetons, sans écart de niveau."""
    return any(
        (_is_fuzzy_match(cert, {known}) and _level_safe(cert, known))
        or _tokens_overlap(cert, {known})
        for known in known_certs
    )


def _post_strings(posts: List[Dict[str, Any]]) -> List[str]:
    return [s for p in posts for key in _POST_TEXT_KEYS for s in _collect_strings(p.get(key))]


def _post_label(post: Dict[str, Any]) -> str:
    return f"{_profile_title(post) or '?'} chez {post.get('company') or post.get('entreprise') or '?'}"


def _stack_terms(post: Dict[str, Any]) -> Dict[str, str]:
    """Technologies déclarées d'un poste : forme normalisée -> forme d'origine."""
    terms: Dict[str, str] = {}
    for raw in _collect_strings(post.get("stack")) + _collect_strings(post.get("technologies")):
        term = _clean_str(raw)
        if len(term) >= 2 and term not in STOPWORDS and not term.isdigit():
            terms[term] = raw.strip()
    return terms


def _short_term_in(raw: str, bullet: str) -> bool:
    """Terme de pile <= 3 caractères (« Go ») hors « go-live », « Go/No Go », « R&D » et « 500 Go »."""
    for m in re.finditer(rf"(?<![\w&-]){re.escape(raw)}(?![\w&-])(?!(?i:\s*/\s*no\b))", bullet):
        if not re.search(r"(?:\d|\bno)\s*$", bullet[: m.start()], re.IGNORECASE):
            return True
    return False
